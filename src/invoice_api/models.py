"""Database tables, as SQLAlchemy models.

Money is `NUMERIC`, never floating point. Prices that follow from other
columns are generated by PostgreSQL, and invoice totals are never stored:
they are summed from the current product prices whenever they are read, so
they can't go stale (see docs/database.md).
"""

import datetime as dt
from decimal import Decimal
from enum import StrEnum

from sqlalchemy import (
    CheckConstraint,
    Computed,
    Date,
    Enum,
    ForeignKey,
    Identity,
    Index,
    Numeric,
    String,
    Text,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

MONEY = Numeric(12, 2)
UNIT_TAX_SQL = "round(unit_price_without_tax * vat_rate / 100, 2)"


class Base(DeclarativeBase):
    pass


class Unit(StrEnum):
    HOUR = "hour"
    DAY = "day"
    PIECE = "piece"


class Customer(Base):
    __tablename__ = "customers"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    first_name: Mapped[str] = mapped_column(Text)
    last_name: Mapped[str] = mapped_column(Text)
    address: Mapped[str] = mapped_column(Text)
    zip_code: Mapped[str] = mapped_column(String(10))
    city: Mapped[str] = mapped_column(Text)
    country: Mapped[str] = mapped_column(Text)
    country_code: Mapped[str] = mapped_column(String(2))

    __table_args__ = (
        # Trigram indexes make "contains" searches (ILIKE '%dup%') use an index,
        # in both name orders, as the search box allows.
        Index(
            "ix_customers_first_last_trgm",
            text("(first_name || ' ' || last_name) gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index(
            "ix_customers_last_first_trgm",
            text("(last_name || ' ' || first_name) gin_trgm_ops"),
            postgresql_using="gin",
        ),
    )


class Product(Base):
    __tablename__ = "products"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    label: Mapped[str] = mapped_column(Text)
    unit: Mapped[Unit] = mapped_column(
        Enum(Unit, name="unit", values_callable=lambda e: [m.value for m in e])
    )
    vat_rate: Mapped[Decimal] = mapped_column(Numeric(3, 1))
    unit_price_without_tax: Mapped[Decimal] = mapped_column(MONEY)
    unit_tax: Mapped[Decimal] = mapped_column(MONEY, Computed(UNIT_TAX_SQL, persisted=True))
    unit_price: Mapped[Decimal] = mapped_column(
        MONEY, Computed(f"unit_price_without_tax + {UNIT_TAX_SQL}", persisted=True)
    )

    __table_args__ = (
        CheckConstraint("vat_rate IN (0, 5.5, 10, 20)", name="ck_products_vat_rate"),
        CheckConstraint("unit_price_without_tax >= 0", name="ck_products_price_positive"),
        Index(
            "ix_products_label_trgm",
            "label",
            postgresql_using="gin",
            postgresql_ops={"label": "gin_trgm_ops"},
        ),
    )


class Invoice(Base):
    __tablename__ = "invoices"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    customer_id: Mapped[int | None] = mapped_column(
        ForeignKey("customers.id", ondelete="RESTRICT"), index=True
    )
    finalized: Mapped[bool] = mapped_column(server_default=text("false"))
    paid: Mapped[bool] = mapped_column(server_default=text("false"))
    date: Mapped[dt.date | None] = mapped_column(Date)
    deadline: Mapped[dt.date | None] = mapped_column(Date, index=True)

    customer: Mapped[Customer | None] = relationship(lazy="raise")
    lines: Mapped[list["InvoiceLine"]] = relationship(
        back_populates="invoice",
        cascade="all, delete-orphan",
        order_by="InvoiceLine.id",
        lazy="raise",
    )

    __table_args__ = (
        # The same rule the API enforces, kept by the database as well.
        CheckConstraint("finalized OR NOT paid", name="ck_invoices_paid_needs_finalized"),
    )


class InvoiceLine(Base):
    __tablename__ = "invoice_lines"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    invoice_id: Mapped[int] = mapped_column(
        ForeignKey("invoices.id", ondelete="CASCADE"), index=True
    )
    product_id: Mapped[int] = mapped_column(
        ForeignKey("products.id", ondelete="RESTRICT"), index=True
    )
    quantity: Mapped[int]

    invoice: Mapped[Invoice] = relationship(back_populates="lines", lazy="raise")
    product: Mapped[Product] = relationship(lazy="raise")

    __table_args__ = (CheckConstraint("quantity > 0", name="ck_invoice_lines_quantity_positive"),)
